/**
 * Record kinds stored by Cyclica (schemaVersion 1).
 *
 * Rules:
 *  - Only what the user entered is stored. Every field except the essentials is optional:
 *    an absent field means "not recorded", never "none" or zero.
 *  - "None" is recorded explicitly (e.g. a `dayStatus` "No headache today", or severity 0 = "none" where that is a choice the user made).
 *  - Calculated values (cycle day, sleep duration from bed/wake times, ...) are derived at read time, never stored.
 */
import { z } from 'zod';
import { LOCAL_DATE_RE, LOCAL_DATE_TIME_RE } from '../time';
import { BaseRecord } from './base';

export const LocalDateZ = z.string().regex(LOCAL_DATE_RE, 'Expected a date (YYYY-MM-DD)');
export const LocalDateTimeZ = z.string().regex(LOCAL_DATE_TIME_RE, 'Expected a date-time with offset');

const scale = (min: number, max: number) => z.number().int().min(min).max(max);
/** 0 none · 1 mild · 2 moderate · 3 severe */
const Severity4 = scale(0, 3);

/** Day-level record: belongs to a calendar day, no time of day. */
const DayBase = BaseRecord.extend({ date: LocalDateZ });
/** Timed record: `occurredAt` is the wall-clock time with offset; `date` is its calendar day (kept in sync on save). */
const TimedBase = BaseRecord.extend({ date: LocalDateZ, occurredAt: LocalDateTimeZ });

// ---------- Pillar 1: menstrual cycle ----------

export const FLOWS = ['spotting', 'light', 'medium', 'heavy'] as const;
export const Bleeding = DayBase.extend({
  kind: z.literal('bleeding'),
  flow: z.enum(FLOWS),
  unusual: z.boolean().optional(),
});

export const CYCLE_SYMPTOMS = [
  'cramps',
  'breastTenderness',
  'bloating',
  'moodChanges',
  'skinChanges',
  'acne',
  'fatigue',
  'appetiteChanges',
] as const;
export const CycleSymptoms = DayBase.extend({
  kind: z.literal('cycleSymptoms'),
  /** Built-in symptom keys or the user's own custom labels. Intensity 1–3 is optional. */
  symptoms: z.array(z.object({ key: z.string().min(1).max(60), intensity: scale(1, 3).optional() })).max(40),
});

export const MUCUS = ['dry', 'sticky', 'creamy', 'watery', 'eggWhite'] as const;
export const LH_RESULTS = ['negative', 'positive', 'invalid'] as const;
export const FertilityObs = DayBase.extend({
  kind: z.literal('fertilityObs'),
  mucus: z.enum(MUCUS).optional(),
  bbtCelsius: z.number().min(34).max(39).optional(),
  bbtTime: z.string().regex(/^\d{2}:\d{2}$/).optional(),
  lhTest: z.enum(LH_RESULTS).optional(),
});

// ---------- Pillar 2: headaches ----------

export const HEAD_LOCATIONS = ['forehead', 'temples', 'leftSide', 'rightSide', 'top', 'back', 'behindEyes', 'neck', 'wholeHead'] as const;
export const HEAD_CHARACTER = ['throbbing', 'pressing', 'stabbing', 'dull', 'burning'] as const;
export const HEAD_ASSOCIATED = ['nausea', 'lightSensitivity', 'soundSensitivity', 'visualDisturbance', 'dizziness', 'neckTension'] as const;
export const IMPACT = ['none', 'some', 'unable'] as const;
export const MED_HELPED = ['yes', 'partly', 'no', 'unsure'] as const;

export const Headache = TimedBase.extend({
  kind: z.literal('headache'),
  /** Wall-clock end time, if known. Alternatively durationMinutes. */
  endAt: LocalDateTimeZ.optional(),
  durationMinutes: z.number().int().min(1).max(60 * 24 * 7).optional(),
  severity: scale(1, 10).optional(),
  locations: z.array(z.enum(HEAD_LOCATIONS)).optional(),
  character: z.array(z.enum(HEAD_CHARACTER)).optional(),
  pattern: z.enum(['continuous', 'intermittent']).optional(),
  associated: z.array(z.enum(HEAD_ASSOCIATED)).optional(),
  otherSymptoms: z.string().max(300).optional(),
  impact: z.enum(IMPACT).optional(),
  /** Ids of `medication` records taken for this headache. */
  medicationIds: z.array(z.uuid()).optional(),
  medicationHelped: z.enum(MED_HELPED).optional(),
  /** A diagnosis label the USER already received from a clinician. Never generated by the app. */
  userDiagnosisLabel: z.string().max(100).optional(),
});

// ---------- Pillar 3: digestion ----------

export const Digestion = TimedBase.extend({
  kind: z.literal('digestion'),
  bloating: Severity4.optional(),
  discomfort: Severity4.optional(),
  pain: Severity4.optional(),
  gas: z.boolean().optional(),
  constipation: z.boolean().optional(),
  diarrhoea: z.boolean().optional(),
  /** Overall digestive comfort 1 (very poor) – 5 (very good). */
  comfort: scale(1, 5).optional(),
  bowelMovement: z.boolean().optional(),
  /** Bristol Stool Form Scale type 1–7, only if a bowel movement is recorded. */
  bristol: scale(1, 7).optional(),
});

// ---------- Pillar 4: energy, sleepiness, sleep ----------

export const SLOTS = ['morning', 'afternoon', 'evening'] as const;
export const CheckIn = TimedBase.extend({
  kind: z.literal('checkIn'),
  slot: z.enum(SLOTS).optional(),
  energy: scale(1, 10).optional(),
  clarity: scale(1, 10).optional(),
  motivation: scale(1, 10).optional(),
  /** Daytime sleepiness 1 (wide awake) – 10 (can barely stay awake). Separate from energy. */
  sleepiness: scale(1, 10).optional(),
  difficultyStayingAwake: z.boolean().optional(),
  physicallyExhausted: z.boolean().optional(),
  mentallyTired: z.boolean().optional(),
});

export const RESTED = ['yes', 'somewhat', 'no'] as const;
export const Sleep = DayBase.extend({
  kind: z.literal('sleep'),
  /** `date` is the WAKE-UP day. */
  bedtime: LocalDateTimeZ.optional(),
  wakeTime: LocalDateTimeZ.optional(),
  /** Only when entered directly; otherwise duration is calculated from bedtime and wake time. */
  durationMinutes: z.number().int().min(0).max(24 * 60).optional(),
  awakenings: z.number().int().min(0).max(50).optional(),
  /** 1 very poor – 5 very good */
  quality: scale(1, 5).optional(),
  rested: z.enum(RESTED).optional(),
});

// ---------- Contextual journal ----------

export const MEAL_TYPES = ['breakfast', 'lunch', 'dinner', 'snack', 'drink'] as const;
export const PORTIONS = ['small', 'medium', 'large'] as const;
export const Meal = TimedBase.extend({
  kind: z.literal('meal'),
  mealType: z.enum(MEAL_TYPES).optional(),
  /** Ids of reusable `foodItem` records. */
  foodItemIds: z.array(z.uuid()).optional(),
  description: z.string().max(1000).optional(),
  portion: z.enum(PORTIONS).optional(),
  /** Food categories the user chose to monitor (e.g. dairy, gluten). User-entered, never inferred. */
  categories: z.array(z.string().min(1).max(40)).optional(),
});

export const FoodItem = BaseRecord.extend({
  kind: z.literal('foodItem'),
  name: z.string().min(1).max(100),
  ingredients: z.array(z.string().min(1).max(60)).optional(),
  categories: z.array(z.string().min(1).max(40)).optional(),
  archived: z.boolean().optional(),
});

export const LIFESTYLE_TYPES = [
  'water',
  'caffeine',
  'alcohol',
  'exercise',
  'stress',
  'workload',
  'travel',
  'illness',
  'event',
] as const;
export const INTENSITY = ['light', 'moderate', 'vigorous'] as const;
export const Lifestyle = TimedBase.extend({
  kind: z.literal('lifestyle'),
  type: z.enum(LIFESTYLE_TYPES),
  /** Amount in `unit` (e.g. 250 ml water, 1 cup coffee, 2 drinks). */
  amount: z.number().min(0).max(100_000).optional(),
  unit: z.string().max(20).optional(),
  durationMinutes: z.number().int().min(0).max(60 * 24).optional(),
  intensity: z.enum(INTENSITY).optional(),
  /** Stress or workload level 1 (very low) – 10 (very high). */
  level: scale(1, 10).optional(),
  /** e.g. exercise type, illness name, event description */
  label: z.string().max(100).optional(),
});

export const Medication = TimedBase.extend({
  kind: z.literal('medication'),
  name: z.string().min(1).max(100),
  dose: z.string().max(60).optional(),
  medType: z.enum(['medication', 'supplement']),
});

export const Note = TimedBase.extend({
  kind: z.literal('note'),
  text: z.string().min(1).max(5000),
});

/** Explicit "none" for a day: the user confirmed there was nothing to record in this area. */
export const DAY_STATUS_AREAS = ['bleeding', 'headache', 'digestion'] as const;
export const DayStatus = DayBase.extend({
  kind: z.literal('dayStatus'),
  area: z.enum(DAY_STATUS_AREAS),
  status: z.literal('none'),
});

// ---------- Personal experiments ----------

export const EXPERIMENT_OUTCOMES = ['headacheDay', 'energy', 'sleepiness', 'digestiveSymptom', 'bloating', 'sleepMinutes', 'sleepQuality'] as const;
export const Experiment = BaseRecord.extend({
  kind: z.literal('experiment'),
  title: z.string().min(1).max(120),
  /** What the user changed, in their own words. */
  change: z.string().max(1000).optional(),
  startDate: LocalDateZ,
  plannedEndDate: LocalDateZ.optional(),
  endedDate: LocalDateZ.optional(),
  outcomes: z.array(z.enum(EXPERIMENT_OUTCOMES)).min(1),
});

// ---------- registry ----------

export const SCHEMAS = {
  bleeding: Bleeding,
  cycleSymptoms: CycleSymptoms,
  fertilityObs: FertilityObs,
  headache: Headache,
  digestion: Digestion,
  checkIn: CheckIn,
  sleep: Sleep,
  meal: Meal,
  foodItem: FoodItem,
  lifestyle: Lifestyle,
  medication: Medication,
  note: Note,
  dayStatus: DayStatus,
  experiment: Experiment,
} as const;

export type Kind = keyof typeof SCHEMAS;
export type RecordOf<K extends Kind> = z.infer<(typeof SCHEMAS)[K]>;
export type AnyRecord = { [K in Kind]: RecordOf<K> }[Kind];

export type BleedingRec = RecordOf<'bleeding'>;
export type CycleSymptomsRec = RecordOf<'cycleSymptoms'>;
export type FertilityObsRec = RecordOf<'fertilityObs'>;
export type HeadacheRec = RecordOf<'headache'>;
export type DigestionRec = RecordOf<'digestion'>;
export type CheckInRec = RecordOf<'checkIn'>;
export type SleepRec = RecordOf<'sleep'>;
export type MealRec = RecordOf<'meal'>;
export type FoodItemRec = RecordOf<'foodItem'>;
export type LifestyleRec = RecordOf<'lifestyle'>;
export type MedicationRec = RecordOf<'medication'>;
export type NoteRec = RecordOf<'note'>;
export type DayStatusRec = RecordOf<'dayStatus'>;
export type ExperimentRec = RecordOf<'experiment'>;

export function isKind(k: string): k is Kind {
  return k in SCHEMAS;
}

export function schemaFor(kind: string): z.ZodType | undefined {
  return isKind(kind) ? SCHEMAS[kind] : undefined;
}

/** Kinds that carry a time of day (shown on the timeline at that time). */
export function isTimed(r: { kind: string }): r is { kind: string; occurredAt: string; date: string } {
  return 'occurredAt' in r && typeof (r as { occurredAt?: unknown }).occurredAt === 'string';
}
